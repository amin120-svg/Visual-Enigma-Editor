'use strict'

const { contextBridge, ipcRenderer } = require('electron')

// No generic IPC, Node.js API, shell, or arbitrary filesystem path is exposed to the renderer.
contextBridge.exposeInMainWorld('veeDesktop', Object.freeze({
  runtimeStatus: () => ipcRenderer.invoke('vee:mode:status'),
  setOfflineMode: enabled => ipcRenderer.invoke('vee:mode:set', enabled),
  listProjects: () => ipcRenderer.invoke('vee:projects:list'),
  listProjectStarters: () => ipcRenderer.invoke('vee:projects:starters'),
  createProject: (name, starterId = 'static') => ipcRenderer.invoke('vee:projects:create', { name, starterId }),
  openProjectFolder: () => ipcRenderer.invoke('vee:projects:open-folder'),
  listFiles: projectId => ipcRenderer.invoke('vee:files:list', projectId),
  readFile: (projectId, relativePath) => ipcRenderer.invoke('vee:files:read', projectId, relativePath),
  createFile: (projectId, relativePath) => ipcRenderer.invoke('vee:files:create', projectId, relativePath),
  createDirectory: (projectId, relativePath) => ipcRenderer.invoke('vee:folders:create', projectId, relativePath),
  writeFile: (projectId, relativePath, content, expectedContent) => ipcRenderer.invoke('vee:files:write', projectId, relativePath, content, expectedContent),
  aiStatus: () => ipcRenderer.invoke('vee:ai:status'),
  saveAISettings: settings => ipcRenderer.invoke('vee:ai:save', settings),
  removeAIKey: () => ipcRenderer.invoke('vee:ai:remove-key'),
  generateAIProposal: request => ipcRenderer.invoke('vee:ai:generate', request),
  onlineStatus: () => ipcRenderer.invoke('vee:online:status'),
  onlineConnect: baseUrl => ipcRenderer.invoke('vee:online:connect', baseUrl),
  onlineDisconnect: () => ipcRenderer.invoke('vee:online:disconnect'),
  onlineLogin: input => ipcRenderer.invoke('vee:online:login', input),
  onlineRegister: input => ipcRenderer.invoke('vee:online:register', input),
  onlineLogout: () => ipcRenderer.invoke('vee:online:logout'),
  onlineLogoutOtherSessions: password => ipcRenderer.invoke('vee:online:logout-other-sessions', password),
  onlineUpdateProfile: input => ipcRenderer.invoke('vee:online:update-profile', input),
  onlineEntitlements: () => ipcRenderer.invoke('vee:online:entitlements'),
  onlineRequestPasswordReset: email => ipcRenderer.invoke('vee:online:request-password-reset', email),
  onlineConfirmPasswordReset: input => ipcRenderer.invoke('vee:online:confirm-password-reset', input),
  communityList: () => ipcRenderer.invoke('vee:online:community-list'),
  communityMine: () => ipcRenderer.invoke('vee:online:community-mine'),
  communityInspectFile: () => ipcRenderer.invoke('vee:online:community-inspect'),
  communitySubmit: input => ipcRenderer.invoke('vee:online:community-submit', input),
  communityDownload: id => ipcRenderer.invoke('vee:online:community-download', id),
  agentSettings: () => ipcRenderer.invoke('vee:agent:settings'),
  agentSaveSettings: input => ipcRenderer.invoke('vee:agent:save-settings', input),
  agentPair: input => ipcRenderer.invoke('vee:agent:pair', input),
  agentDisconnect: () => ipcRenderer.invoke('vee:agent:disconnect'),
  agentStatus: () => ipcRenderer.invoke('vee:agent:status'),
  agentInspectProject: projectId => ipcRenderer.invoke('vee:agent:inspect-project', projectId),
  agentPrepareRelease: input => ipcRenderer.invoke('vee:agent:prepare-release', input),
  agentPublish: input => ipcRenderer.invoke('vee:agent:publish', input),
  agentRollback: input => ipcRenderer.invoke('vee:agent:rollback', input),
}))
